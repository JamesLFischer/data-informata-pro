import csv, html, datetime, subprocess, shutil, os
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment

LOG_COLS = ["Prompt ID", "Cluster / Category", "Standardized Prompt", "AI Engine Evaluated", "Model",
            "{brand} Mentioned (Yes/No)", "{product} Mentioned (Yes/No)", "Prominence Rank", "Position Weight",
            "Sentiment", "ARS Sentiment Score", "Core Product Drivers Cited", "Technical Accuracy / Fidelity",
            "Cited Sources / Domains", "Strategic Notes / Gaps", "Scored By", "Raw Answer"]
DASH_COLS = ["AI Engine", "Prompts Evaluated", "Total Mentions", "#1 Recommendations", "Top 3 Mentions",
             "Overall SoM %", "Net ARS Score (0-100)", "Citation Fidelity"]

def log_cols(cfg):
    prod = cfg.get("products", ["Product"])[0] if cfg.get("products") else "Product"
    return [c.format(brand=cfg["brand"], product=prod) for c in LOG_COLS]

def to_row(cfg, r):
    s = r["s"]; yn = lambda b: "Yes" if b else "No"
    return [r["pid"], r["cluster"], r["prompt"], r["engine"], r["model"], yn(s["brand_mentioned"]), yn(s["product_mentioned"]),
            s["rank"], s["weight"], s["sentiment"], s["score"], s["features"], s["accuracy"], s["domains"], s["gaps"],
            s["scored_by"], r["text"]]

def dashboard(results):
    out = []
    for eng in dict.fromkeys(r["engine"] for r in results):
        rs = [r["s"] for r in results if r["engine"] == eng and not r.get("error")]; n = len(rs)
        if not n: out.append([eng, 0, 0, 0, 0, "n/a", "n/a", "n/a"]); continue
        judged = [s for s in rs if s["accuracy"] in ("Accurate", "Partially Accurate", "Inaccurate")]
        fid = f"{100*sum(s['accuracy']=='Accurate' for s in judged)/len(judged):.1f}%" if judged else "n/a"
        out.append([eng, n, sum(s["rank"] != "Not Mentioned" for s in rs), sum(s["rank"] == "#1 Top Rec" for s in rs),
                    sum(s["rank"] == "Top 3" for s in rs), f"{100*sum(s['weight'] for s in rs)/n:.1f}%",
                    f"{sum(s['score'] for s in rs)/n:.1f}", fid])
    return out

def _mentions(text, name):
    import re
    return re.search(r"(?<!\w)" + re.escape(name.lower()) + r"(?!\w)", text.lower()) is not None

def share_of_voice(cfg, results):
    """Brand vs competitors: % of successful answers per engine that mention each name (competitive Share of Model)."""
    names = [cfg["brand"]] + list(cfg.get("competitors", []))
    aliases = {cfg["brand"]: [cfg["brand"]] + cfg.get("brand_aliases", [])}
    engines = list(dict.fromkeys(r["engine"] for r in results))
    rows = []
    for n in names:
        row = [n]
        for eng in engines + ["All engines"]:
            rs = [r for r in results if not r.get("error") and (eng == "All engines" or r["engine"] == eng)]
            hit = sum(any(_mentions(r["text"], a) for a in aliases.get(n, [n])) for r in rs)
            row.append(f"{100*hit/len(rs):.1f}%" if rs else "n/a")
        rows.append(row)
    rows.sort(key=lambda r: -float(r[-1].rstrip("%")) if r[-1] != "n/a" else 0)
    return ["Brand"] + engines + ["All engines"], rows

def write_all(cfg, results, outdir, example=False):
    os.makedirs(outdir, exist_ok=True)
    slug = cfg["brand"].replace(" ", "_")
    cols, rows, dash = log_cols(cfg), [to_row(cfg, r) for r in results], dashboard(results)
    p = {k: os.path.join(outdir, f"{slug}_{k}") for k in ["evaluation_log.csv", "executive_dashboard.csv", "tracker.xlsx", "report.html", "report.pdf"]}
    for path, c, rr in [(p["evaluation_log.csv"], cols, rows), (p["executive_dashboard.csv"], DASH_COLS, dash)]:
        with open(path, "w", newline="") as f:
            w = csv.writer(f)
            if example: w.writerow(["EXAMPLE DATA - generated by mock engine, not real AI results"])
            w.writerow(c); w.writerows(rr)
    sov_cols, sov = share_of_voice(cfg, results)
    p["share_of_voice.csv"] = os.path.join(outdir, f"{slug}_share_of_voice.csv")
    with open(p["share_of_voice.csv"], "w", newline="") as f:
        w = csv.writer(f)
        if example: w.writerow(["EXAMPLE DATA - generated by mock engine, not real AI results"])
        w.writerow(sov_cols); w.writerows(sov)
    import json
    cost = {"total_usd": round(sum(r.get("cost", 0) for r in results), 4), "calls": len(results),
            "by_engine": {e_: round(sum(r.get("cost", 0) for r in results if r["engine"] == e_), 4) for e_ in dict.fromkeys(r["engine"] for r in results)},
            "note": "answer calls only; Perplexity is billed-exact, others estimated from token list prices; judge calls not included"}
    p["cost.json"] = os.path.join(outdir, "cost.json"); json.dump(cost, open(p["cost.json"], "w"), indent=1)
    wb = Workbook(); hdr = PatternFill("solid", fgColor=cfg.get("brand_color", "1F4E79").lstrip("#"))
    for i, (title, c, rr) in enumerate([("Executive Dashboard", DASH_COLS, dash), ("Evaluation Log", cols, rows)]):
        ws = wb.active if i == 0 else wb.create_sheet(); ws.title = title
        if example: ws.append(["EXAMPLE DATA - mock engine, not real AI results"]); ws["A1"].font = Font(bold=True, color="C00000")
        ws.append(c)
        for cell in ws[ws.max_row]: cell.font = Font(bold=True, color="FFFFFF"); cell.fill = hdr
        for r in rr: ws.append(r)
        for col in ws.columns:
            ws.column_dimensions[col[0].column_letter].width = min(60, max(10, max(len(str(x.value or ""))for x in col[:30]) + 2))
        for row in ws.iter_rows(): [setattr(c, "alignment", Alignment(wrap_text=True, vertical="top")) for c in row]
        ws.freeze_panes = ws.cell(row=3 if example else 2, column=1)
    wb.save(p["tracker.xlsx"])
    mom = None
    if not example and not outdir.rstrip("/").endswith("_SMOKE"):
        from . import history as H
        prev, basis = H.previous_run(os.path.dirname(os.path.abspath(outdir)), H.run_time(outdir) or datetime.datetime.now())
        if prev:
            cur = {H.canon(d[0]): {"n": d[1], "som": H._pct(d[5]), "mentions": round(100 * d[2] / d[1], 1), "top1": round(100 * d[3] / d[1], 1),
                                   "sentiment": H._pct(d[6]), "fidelity": H._pct(d[7])} for d in dash if d[1]}
            mom = {"baseline": os.path.basename(prev), "basis": basis, "rows": H.deltas(cur, H.metrics(prev))}
        else: mom = {"baseline": None, "basis": "first run - no baseline yet", "rows": []}
        p["mom.json"] = os.path.join(outdir, "mom.json"); json.dump(mom, open(p["mom.json"], "w"), indent=1)
    with open(p["report.html"], "w") as f: f.write(render_html(cfg, results, dash, example, (sov_cols, sov), mom))
    chrome = shutil.which("google-chrome") or shutil.which("chromium")
    if chrome:
        subprocess.run([chrome, "--headless", "--no-sandbox", "--disable-gpu", "--no-pdf-header-footer",
                        f"--print-to-pdf={p['report.pdf']}", "file://" + os.path.abspath(p["report.html"])],
                       capture_output=True, timeout=120)
    return p

def mom_html(mom):
    """Month-over-month section. Deltas are percentage points (pts for sentiment)."""
    from .history import METRICS, fmt_delta
    e = html.escape
    if not mom: return ""
    if not mom.get("baseline"): return "<h2>Change vs Last Month</h2><p class=muted>This is the first tracked run for this client &mdash; it becomes the baseline for next month's comparison.</p>"
    cols = [m for m in METRICS]
    head = "<tr><th>AI Engine</th>" + "".join(f"<th>{e(lab)}</th>" for _, lab, _, _ in cols) + "<th>Notes</th></tr>"
    def cell(v):
        col = "#1a7f37" if (v["delta"] or 0) > 0 else "#c62828" if (v["delta"] or 0) < 0 else "#555"
        now = "&mdash;" if v["now"] is None else f"{v['now']:.1f}"
        return f"<td>{now} <span style='color:{col}'>{e(fmt_delta(v['delta']))}</span></td>"
    body = "".join(f"<tr><td>{e(r['engine'])}</td>" + "".join(cell(r[k]) for k, _, _, _ in cols) + f"<td>{e(r['note'])}</td></tr>" for r in mom["rows"])
    return (f"<h2>Change vs Last Month</h2><p class=muted>Compared with run {e(mom['baseline'])} ({e(mom['basis'])}). Arrows show the change in percentage points "
            "(sentiment in points). Rates are per prompt evaluated. Treat deltas flagged in Notes with caution.</p><table>" + head + body + "</table>")

