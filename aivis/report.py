    for c in clusters:
        cells = ""
        for eng in engines:
            rs = [r["s"] for r in results if r["cluster"] == c and r["engine"] == eng and not r.get("error")]
            som = 100 * sum(s["weight"] for s in rs) / len(rs) if rs else 0
            cells += f'<td style="background:rgba(31,140,80,{som/130:.2f})">{som:.0f}%</td>'
        cl_rows += f"<tr><td>{e(c)}</td>{cells}</tr>"
    gaps = [r for r in results if r["s"]["rank"] in ("Not Mentioned", "Incidental Mention", "Top 3")]
    gap_rows = "".join(f"<tr><td>{e(r['pid'])}</td><td>{e(r['engine'])}</td><td>{e(r['prompt'])}</td><td>{e(r['s']['rank'])}</td><td>{e(r['s']['gaps'])}</td></tr>" for r in gaps[:40])
    doms = {}
